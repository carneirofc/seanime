func writeZodSchemasFile(selected *selectedStructs, outDir string) error {
	order, backEdges, err := zodEmissionOrder(selected)
	if err != nil {
		return err
	}

	outPath := filepath.Join(outDir, zodSchemasFileName)
	osFile, err := os.Create(outPath)
	if err != nil {
		return fmt.Errorf("creating %s: %w", outPath, err)
	}
	defer osFile.Close()
	f := newErrWriter(osFile)

	f.WriteString("// This code was generated by codegen/main.go. DO NOT EDIT.\n")
	f.WriteString("//\n")
	f.WriteString("// Runtime schemas for the types in ./types.ts. Optional fields use .nullish()\n")
	f.WriteString("// because Go marshals a nil pointer, slice or map as null rather than omitting\n")
	f.WriteString("// the key, and objects are loose so fields the generator does not know about are\n")
	f.WriteString("// preserved rather than stripped.\n\n")
	f.WriteString(`import { z } from "zod"` + "\n\n")

	for _, goStruct := range order {
		writeZodSchema(f, goStruct, backEdges[goStruct.FormattedName])
	}

	return f.Err()
}

// writeZodSchema emits one schema. lazyRefs names the referenced types that must
// be emitted as getters because they close a dependency cycle.
func writeZodSchema(f *errWriter, goStruct *GoStruct, lazyRefs map[string]bool) {
	name := goStruct.FormattedName + zodSchemaSuffix

	f.Printf("/** %s.%s — %s */\n", goStruct.Package, goStruct.Name, goStruct.Filename)

	// A string alias with declared constants becomes an enum, plus a values array
	// so the UI can build option lists from it instead of hardcoding them.
	if goStruct.AliasOf != nil && len(goStruct.AliasOf.DeclaredValues) > 0 {
		values := strings.Join(goStruct.AliasOf.DeclaredValues, ", ")
		f.Printf("export const %sValues = [%s] as const\n", goStruct.FormattedName, values)
		f.Printf("export const %s = z.enum(%sValues)\n\n", name, goStruct.FormattedName)
		return
	}

	if len(goStruct.Fields) > 0 {
		f.Printf("export const %s = z.looseObject({\n", name)
		for _, field := range goStruct.Fields {
			if field.JsonName == "" {
				// Not serialized (json:"-"), so it never appears in a payload.
				continue
			}
			expr := fieldSchema(field)
			if referencesAny(expr, lazyRefs) {
				// A getter defers resolution, which is how zod 4 expresses a
				// recursive schema.
				f.Printf("    get %s() { return %s },\n", quoteJSKeyForGetter(field.JsonName), expr)
				continue
			}
			f.Printf("    %s: %s,\n", quoteJSKey(field.JsonName), expr)
		}
		f.WriteString("})\n\n")
		return
	}

	if goStruct.AliasOf != nil {
		f.Printf("export const %s = %s\n\n", name, tsTypeToZod(goStruct.AliasOf.TypescriptType))
		return
	}

	// No fields and no alias: an empty struct still has to exist, since other
	// schemas reference it.
	f.Printf("export const %s = z.looseObject({})\n\n", name)
}

// referencesAny reports whether a rendered expression refers to any of the given
// schema identifiers.
func referencesAny(expr string, schemaNames map[string]bool) bool {
	if len(schemaNames) == 0 {
		return false
	}
	for _, ref := range referencedSchemaNames(expr) {
		if schemaNames[ref] {
			return true
		}
	}
	return false
}

// quoteJSKeyForGetter renders a getter name. A getter cannot use a quoted key the
// way a plain property can, so a name that is not a bare identifier is emitted in
// brackets as a computed getter.
func quoteJSKeyForGetter(name string) string {
	if isSafeJSIdentifier(name) && name != "" {
		return name
	}
	return "[" + quoteJSKey(name) + "]"
}

