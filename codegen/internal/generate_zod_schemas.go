func structKey(goStruct *GoStruct) string {
	return goStruct.Package + "." + goStruct.Name
}

// generatedSchemaNames is the set of schema identifiers schemas.ts declares.
func generatedSchemaNames(selected *selectedStructs) map[string]bool {
	names := make(map[string]bool, len(selected.ByKey))
	for _, goStruct := range selected.All() {
		names[goStruct.FormattedName+zodSchemaSuffix] = true
	}
	return names
}

// zodEmissionOrder topologically sorts the selected structs so that no schema
// references a const declared later in the file.
//
// The graph is built from the SCHEMA IDENTIFIERS each struct's rendered expressions
// refer to, not from the Go types its fields point at. Those differ: two packages
// can share a type-name prefix ("habari" and "vendor_habari" both render as
// "Habari_"), so a field pointing at a Go type outside the selected set can still
// emit a reference to a schema inside it. The rendered text is what the file
// contains, so it is the only sound basis for ordering.
//
// Where a cycle makes ordering impossible, the schema names that close the cycle are
// reported in backEdges and the emitter renders those properties as getters. Only one
// type is self-referential today (LibraryExplorer_FileTreeNodeJSON), but cycles are
// detected generally so a new one keeps working.
//
// Returns an error on a duplicate schema name: two selected structs formatting to the
// same TypeScript name would declare the same const twice, which is a compile error in
// the generated file. types.ts has the same constraint, so this cannot happen today --
// but it should fail loudly rather than emit broken code if it starts to.
func zodEmissionOrder(selected *selectedStructs) (order []*GoStruct, backEdges map[string]map[string]bool, err error) {
	all := selected.All()

	byName := make(map[string]*GoStruct, len(all))
	for _, goStruct := range all {
		if prev, ok := byName[goStruct.FormattedName]; ok {
			return nil, nil, fmt.Errorf(
				"duplicate generated type name %q (from %s and %s): schemas.ts would declare the same const twice",
				goStruct.FormattedName, structKey(prev), structKey(goStruct))
		}
		byName[goStruct.FormattedName] = goStruct
	}

	const (
		white = 0
		grey  = 1
		black = 2
	)
	color := make(map[string]int, len(all))
	backEdges = make(map[string]map[string]bool)
	order = make([]*GoStruct, 0, len(all))

	var visit func(goStruct *GoStruct)
	visit = func(goStruct *GoStruct) {
		name := goStruct.FormattedName
		color[name] = grey

		for _, depName := range dependencySchemaNames(goStruct, byName) {
			switch color[depName] {
			case grey:
				// Cycle: this reference has to be deferred to a getter.
				if backEdges[name] == nil {
					backEdges[name] = make(map[string]bool)
				}
				backEdges[name][depName+zodSchemaSuffix] = true
			case white:
				visit(byName[depName])
			}
		}

		color[name] = black
		order = append(order, goStruct)
	}

	// Iterate in the already-sorted order so emission is deterministic.
	for _, goStruct := range all {
		if color[goStruct.FormattedName] == white {
			visit(goStruct)
		}
	}

	return order, backEdges, nil
}

// dependencySchemaNames returns the FormattedNames of the selected structs whose
// schemas goStruct's own schema refers to, sorted for determinism.
func dependencySchemaNames(goStruct *GoStruct, byName map[string]*GoStruct) []string {
	deps := make([]string, 0, len(goStruct.Fields))
	seen := make(map[string]bool, len(goStruct.Fields))

	for _, expr := range renderedSchemaExprs(goStruct) {
		for _, ref := range referencedSchemaNames(expr) {
			typeName := strings.TrimSuffix(ref, zodSchemaSuffix)
			if seen[typeName] {
				continue
			}
			if _, ok := byName[typeName]; !ok {
				// Refers to a type that is not generated; nothing to order against.
				continue
			}
			// A self-reference is included deliberately: visit sees its own colour
			// as grey and records it as the back edge that becomes a getter.
			seen[typeName] = true
			deps = append(deps, typeName)
		}
	}

	slices.SortStableFunc(deps, func(i, j string) int { return cmp.Compare(i, j) })
	return deps
}

// renderedSchemaExprs returns the zod expressions a struct's schema is built from,
// which is what emission order must be derived from.
func renderedSchemaExprs(goStruct *GoStruct) []string {
	if goStruct.AliasOf != nil && len(goStruct.AliasOf.DeclaredValues) > 0 {
		// An enum references nothing.
		return nil
	}

	exprs := make([]string, 0, len(goStruct.Fields)+1)
	for _, field := range goStruct.Fields {
		if field.JsonName == "" {
			continue
		}
		exprs = append(exprs, fieldSchema(field))
	}
	if len(goStruct.Fields) == 0 && goStruct.AliasOf != nil {
		exprs = append(exprs, tsTypeToZod(goStruct.AliasOf.TypescriptType))
	}
	return exprs
}
