const (
	zodSchemasFileName         = "schemas.ts"
	zodEndpointSchemasFileName = "endpoint.schemas.ts"
	zodAssertFileName          = "schemas.assert.ts"

	// The namespace endpoint.schemas.ts imports schemas.ts under, rather than
	// listing several hundred named imports.
	zodSchemasNamespace = "s"
)

// GenerateZodSchemasFile generates runtime zod schemas for the same types that
// GenerateTypescriptFile declares as TypeScript types.
//
// Three files:
//
//   - schemas.ts          one schema per generated type, plus enum value arrays
//   - endpoint.schemas.ts request body schemas and the endpoint -> response schema lookup
//   - schemas.assert.ts   type-only assertions that each schema matches its type
//
// It reuses selectReferencedStructs, so the set of types here is by construction
// the set types.ts declares. If the two ever disagree, schemas.assert.ts stops
// compiling, which is the point.
func GenerateZodSchemasFile(handlersJsonPath string, structsJsonPath string, outDir string, goStructStrs []string) error {
	handlers, err := LoadHandlers(handlersJsonPath)
	if err != nil {
		return err
	}

	goStructs, err := LoadPublicStructs(structsJsonPath)
	if err != nil {
		return err
	}

	selected, err := selectReferencedStructs(handlers, goStructs, goStructStrs)
	if err != nil {
		return err
	}

	if err := os.MkdirAll(outDir, os.ModePerm); err != nil {
		return fmt.Errorf("creating %s: %w", outDir, err)
	}

	if err := writeZodSchemasFile(selected, outDir); err != nil {
		return err
	}
	if err := writeZodEndpointSchemasFile(handlers, generatedSchemaNames(selected), outDir); err != nil {
		return err
	}
	return writeZodAssertFile(selected, outDir)
}

