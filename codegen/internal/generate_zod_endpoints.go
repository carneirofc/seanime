// writeZodAssertFile emits type-only assertions that each schema declares exactly
// the fields its TypeScript type does.
//
// The comparison is on the schema's .shape rather than on z.infer, because a loose
// object's inferred type carries an index signature that widens keyof to string —
// which would make the assertion vacuous.
//
// Key sets, not full types: an optional field's schema is .nullish(), so it infers
// X | null | undefined against the type's X | undefined. Comparing key sets catches
// the drift that actually happens (a field added, removed or renamed on a Go
// struct) without fighting that mismatch.
func writeZodAssertFile(selected *selectedStructs, outDir string) error {
	outPath := filepath.Join(outDir, zodAssertFileName)
	osFile, err := os.Create(outPath)
	if err != nil {
		return fmt.Errorf("creating %s: %w", outPath, err)
	}
	defer osFile.Close()
	f := newErrWriter(osFile)

	f.WriteString("// This code was generated by codegen/main.go. DO NOT EDIT.\n")
	f.WriteString("//\n")
	f.WriteString("// Compile-time proof that ./schemas.ts and ./types.ts agree. This file has no\n")
	f.WriteString("// runtime output; it exists so that `npm run typecheck` fails when a schema and\n")
	f.WriteString("// its type disagree about which fields exist.\n\n")
	f.WriteString(`import type * as T from "./types"` + "\n")
	f.Printf("import * as %s from \"./%s\"\n\n", zodSchemasNamespace, strings.TrimSuffix(zodSchemasFileName, ".ts"))
	f.WriteString("/** Resolves to true only when A and B are the same type, otherwise to never. */\n")
	f.WriteString("type Exact<A, B> = [A] extends [B] ? ([B] extends [A] ? true : never) : never\n\n")

	for _, goStruct := range selected.All() {
		// Only object schemas have a .shape to compare. Enums and aliases have no
		// field set, so there is nothing to drift.
		if len(goStruct.Fields) == 0 {
			continue
		}
		if !hasSerializedField(goStruct) {
			continue
		}

		name := goStruct.FormattedName
		f.Printf("const _%s: Exact<keyof typeof %s.%s%s.shape, keyof T.%s> = true\n",
			name, zodSchemasNamespace, name, zodSchemaSuffix, name)
	}

	return f.Err()
}

// hasSerializedField reports whether any field reaches JSON. A struct whose every
// field is json:"-" emits an empty object schema and no TypeScript body, so there
// is nothing to assert.
func hasSerializedField(goStruct *GoStruct) bool {
	for _, field := range goStruct.Fields {
		if field.JsonName != "" {
			return true
		}
	}
	return false
}
